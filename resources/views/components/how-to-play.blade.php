        <h2>How to play Farkle!</h2>
        <p>Each round, you try to make a scoring hand from an initial roll of six dice.</p>
        <p>Each die in a hand must score.</p>
        <p>After forming a hand, you can choose to end your turn and bank the points, or roll the remaining dice and attempt to make more points.</p>
        <p>Be careful! If you cannot make a scoring hand from a roll, you get a Farkle! You lose all the points from the melds you have set aside and the turn passes to the next player.</p>
        <p>However, if you manage to set aside all six dice for scoring, you get to roll six new ones!</p>
        <p>The winner is the first player to reach 10'000 points.</p>
